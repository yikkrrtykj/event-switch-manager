@dataclass(frozen=True, slots=True)
class Golden:
    text: str
    topic: CommandTopic
    form_id: str
    mode: CommandMode
    target_class: TargetClass
    parameters: dict[str, Any]


def _golden(
    text: str,
    topic: CommandTopic,
    form_id: str,
    mode: CommandMode,
    target_class: TargetClass,
    parameters: dict[str, Any],
) -> Golden:
    return Golden(text, topic, form_id, mode, target_class, parameters)


