@pytest.mark.parametrize("golden", GOLDENS, ids=lambda golden: golden.text)
def test_hand_authored_golden_parses_to_exact_structured_value(
    golden: Golden,
) -> None:
    result = parse_command(golden.text)

    assert result.ok, result.failure_codes
    assert result.failures == ()
    assert result.lex_issues == ()
    command = result.command
    assert command is not None
    assert command.text == golden.text
    assert command.tokens == tuple(golden.text.split(" "))
    assert command.topic is golden.topic
    assert command.form_id == golden.form_id
    assert command.mode is golden.mode
    assert command.target_class is golden.target_class
    assert dict(command.parameters) == golden.parameters
    assert command.json_parameters() == {
        key: list(value) if isinstance(value, tuple) else value
        for key, value in golden.parameters.items()
    }
    form = FORM_BY_ID[golden.form_id]
    assert form.topic is golden.topic
    assert golden.mode in form.modes


def test_golden_corpus_covers_every_reviewed_topic() -> None:
    topics = {golden.topic for golden in GOLDENS}
    assert topics == set(CommandTopic)
    assert len(topics) == 20


def test_golden_corpus_covers_every_grammar_production() -> None:
    covered = {golden.form_id for golden in GOLDENS}
    assert covered == {form.form_id for form in FORMS}


def test_parse_is_deterministic_and_preserves_the_received_text() -> None:
    for golden in GOLDENS:
        first = parse_command(golden.text)
        second = parse_command(golden.text)
        assert first == second
        assert first.command == second.command
        assert first.command is not None
        assert first.command.text is golden.text or first.command.text == golden.text


def test_expected_mode_is_checked_independently() -> None:
    assert parse_command("vlan 10", expected_mode=CommandMode.GLOBAL).ok
    mode_mismatch = parse_command("vlan 10", expected_mode=CommandMode.INTERFACE)
    assert mode_mismatch.failure_codes == ("mode-mismatch",)
    assert parse_command("name Players", expected_mode=CommandMode.VLAN).ok
    assert parse_command(
        "switchport mode access", expected_mode=CommandMode.PORT_CHANNEL,
    ).ok
    assert parse_command(
        "channel-group 1 mode active", expected_mode=CommandMode.INTERFACE,
    ).ok
    channel_group_port_context = parse_command(
        "channel-group 1 mode active", expected_mode=CommandMode.PORT_CHANNEL,
    )
    assert channel_group_port_context.failure_codes == ("mode-mismatch",)
    assert parse_command(
        "interface Port-Channel1", expected_mode=CommandMode.GLOBAL,
    ).ok
    assert not parse_command(
        "interface Port-Channel1", expected_mode=CommandMode.INTERFACE,
    ).ok


def test_structured_parameter_types_are_not_boolean_proxies() -> None:
    vlan = parse_command("vlan 4094").command
    assert vlan is not None
    assert isinstance(vlan.parameter("vlan-id"), int)
    assert vlan.parameter("vlan-id") == 4094

    allowed = parse_command(
        "switchport trunk allowed vlan 10,20,30",
    ).command
    assert allowed is not None
    assert allowed.parameter("vlan-list") == (10, 20, 30)
    assert isinstance(allowed.parameter("vlan-list"), tuple)
    assert allowed.parameter("operation") == "replace"

    channel = parse_command("interface Port-Channel128").command
    assert channel is not None
    assert channel.parameter("port-channel-number") == 128

    priority = parse_command(
        "spanning-tree vlan 10 priority 61440",
    ).command
    assert priority is not None
    assert priority.parameter("priority") == 61440
    assert priority.parameter("vlan-id") == 10

    description = parse_command("description Players desk").command
    assert description is not None
    assert description.parameter("description") == "Players desk"

    admin = parse_command("shutdown").command
    assert admin is not None
    assert admin.parameter("admin-state") == "down"


def test_vlan_list_is_a_replacement_set_not_a_string_prefix() -> None:
    command = parse_command(
        "switchport trunk allowed vlan 10,20,30",
    ).command
    assert command is not None
    assert command.topic is CommandTopic.ALLOWED_VLANS
    assert command.form_id == "allowed-vlans"
    assert command.parameter("operation") == "replace"
    raw_list = command.parameter("vlan-list")
    assert isinstance(raw_list, tuple)
    assert raw_list == (10, 20, 30)
    assert "10,20,30" not in {
        str(value) for value in command.parameters.values()
    }


